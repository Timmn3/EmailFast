def compare_countries(list1, list2):
    set1 = set(list1)
    set2 = set(list2)

    common_countries = sorted(set1 & set2)
    only_in_list1 = sorted(set1 - set2)
    only_in_list2 = sorted(set2 - set1)

    return {
        "common_countries": common_countries,
        "count": len(common_countries),
        "only_in_list1": only_in_list1,
        "only_in_list2": only_in_list2,
    }


